package com.terp.plugin.data;

/**
 * Sales-order line snapshot for a production order. Codes only; no sales entities.
 */
public final class ProductionFromSales {

    private Long sourceOrderId;
    private String sourceOrderNo;
    private Long sourceOrderLineId;
    private String warehouseCode;
    private String warehouseName;
    private String productCode;
    private String productName;
    private String productUnit;
    private double quantity;

    public Long getSourceOrderId() {
        return sourceOrderId;
    }

    public void setSourceOrderId(Long sourceOrderId) {
        this.sourceOrderId = sourceOrderId;
    }

    public String getSourceOrderNo() {
        return sourceOrderNo;
    }

    public void setSourceOrderNo(String sourceOrderNo) {
        this.sourceOrderNo = sourceOrderNo;
    }

    public Long getSourceOrderLineId() {
        return sourceOrderLineId;
    }

    public void setSourceOrderLineId(Long sourceOrderLineId) {
        this.sourceOrderLineId = sourceOrderLineId;
    }

    public String getWarehouseCode() {
        return warehouseCode;
    }

    public void setWarehouseCode(String warehouseCode) {
        this.warehouseCode = warehouseCode;
    }

    public String getWarehouseName() {
        return warehouseName;
    }

    public void setWarehouseName(String warehouseName) {
        this.warehouseName = warehouseName;
    }

    public String getProductCode() {
        return productCode;
    }

    public void setProductCode(String productCode) {
        this.productCode = productCode;
    }

    public String getProductName() {
        return productName;
    }

    public void setProductName(String productName) {
        this.productName = productName;
    }

    public String getProductUnit() {
        return productUnit;
    }

    public void setProductUnit(String productUnit) {
        this.productUnit = productUnit;
    }

    public double getQuantity() {
        return quantity;
    }

    public void setQuantity(double quantity) {
        this.quantity = quantity;
    }
}
