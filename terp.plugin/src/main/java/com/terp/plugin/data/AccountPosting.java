package com.terp.plugin.data;

import java.util.Date;

/**
 * One current-account posting. Plugins must not pass cari entity classes.
 */
public final class AccountPosting {

    public static final String SOURCE_SALES_INVOICE = "SATIS_FATURA";
    public static final String SOURCE_PURCHASE_INVOICE = "SATIN_FATURA";
    public static final String SOURCE_PURCHASE_RECEIPT = "SATIN_KABUL";
    public static final String SOURCE_MANUAL = "CARI_HAREKET";

    private Date movementDate;
    private int direction;
    private String accountCode;
    private String accountName;
    private Double amount;
    private String documentNo;
    private String sourceType;
    private Long sourceId;
    private String notes;

    public Date getMovementDate() {
        return movementDate;
    }

    public void setMovementDate(Date movementDate) {
        this.movementDate = movementDate;
    }

    public int getDirection() {
        return direction;
    }

    public void setDirection(int direction) {
        this.direction = direction;
    }

    public String getAccountCode() {
        return accountCode;
    }

    public void setAccountCode(String accountCode) {
        this.accountCode = accountCode;
    }

    public String getAccountName() {
        return accountName;
    }

    public void setAccountName(String accountName) {
        this.accountName = accountName;
    }

    public Double getAmount() {
        return amount;
    }

    public void setAmount(Double amount) {
        this.amount = amount;
    }

    public String getDocumentNo() {
        return documentNo;
    }

    public void setDocumentNo(String documentNo) {
        this.documentNo = documentNo;
    }

    public String getSourceType() {
        return sourceType;
    }

    public void setSourceType(String sourceType) {
        this.sourceType = sourceType;
    }

    public Long getSourceId() {
        return sourceId;
    }

    public void setSourceId(Long sourceId) {
        this.sourceId = sourceId;
    }

    public String getNotes() {
        return notes;
    }

    public void setNotes(String notes) {
        this.notes = notes;
    }
}
